import { existsSync, rmSync } from "node:fs";
import { join } from "node:path";
import type { FeatureConfig } from "../config.ts";
import { FireShellError, human, log, run, sizeOf } from "../util.ts";

/**
 * A prune rule removes paths from an extracted Gecko runtime.
 * Globs are evaluated relative to the runtime root (the directory holding `firefox`
 * / `libxul.so` / `omni.ja`).
 */
export interface PruneRule {
  id: string;
  /** Glob patterns to delete. `keep` patterns subtract from the match set. */
  remove: string[];
  keep?: string[];
  /** Keep list computed from config, for rules that depend on feature flags. */
  keepFor?: (ctx: PruneContext) => string[];
  enabled: (f: FeatureConfig, ctx: PruneContext) => boolean;
  note: string;
}

export interface PruneContext {
  platform: NodeJS.Platform;
  features: FeatureConfig;
}

export interface PruneReport {
  removed: { id: string; bytes: number; files: number }[];
  totalBytes: number;
  skipped: { id: string; reason: string }[];
}

export const PRUNE_RULES: PruneRule[] = [
  {
    id: "dictionaries",
    remove: ["dictionaries/*.dic", "dictionaries/*.aff"],
    keepFor: (ctx) =>
      ctx.features.locales.flatMap((locale) => [`dictionaries/${locale}.dic`, `dictionaries/${locale}.aff`]),
    enabled: () => true,
    note: "unused Hunspell dictionaries",
  },
  {
    id: "hyphenation",
    remove: ["hyphenation/*.hyf"],
    enabled: () => true,
    note: "hyphenation dictionaries",
  },
  {
    id: "crash-reporting",
    remove: ["crashreporter", "crashreporter.exe", "minidump-analyzer", "minidump-analyzer.exe", "pingsender", "pingsender.exe", "crashreporter.app"],
    enabled: () => true,
    note: "crash reporter and telemetry pingsender (never used in production)",
  },
  {
    id: "updater",
    remove: ["updater", "updater.exe", "updates", "update-settings.ini", "updater.app"],
    enabled: () => true,
    note: "background updater (runtime version is pinned by the app)",
  },
  {
    id: "drm",
    remove: ["gmp-clearkey", "gmp-widevinecdm", "gmp-widevinecdm.app"],
    enabled: (f) => !("drm" in f && (f as FeatureConfig & { drm?: boolean }).drm),
    note: "EME/DRM content decryption modules",
  },
  {
    id: "fonts",
    remove: ["fonts"],
    enabled: (f) => !f.pdf,
    note: "bundled STIX math fonts",
  },
  {
    id: "distribution",
    remove: ["distribution/extensions", "distribution/searchplugins"],
    enabled: () => true,
    note: "upstream distribution payload (regenerated by the launcher)",
  },
  {
    id: "langpacks",
    remove: ["browser/features/langpack-*.xpi"],
    keep: ["browser/features/langpack-en-US@firefox.mozilla.org.xpi"],
    enabled: () => true,
    note: "non-default locale language packs",
  },
];

/**
 * Applies filesystem prune rules to an extracted runtime.
 * Returns what was removed so the caller can report real byte savings.
 */
export function applyPrune(runtimeRoot: string, features: FeatureConfig, platform = process.platform, dryRun = false): PruneReport {
  const report: PruneReport = { removed: [], totalBytes: 0, skipped: [] };

  for (const rule of PRUNE_RULES) {
    if (!rule.enabled(features, { platform, features })) {
      report.skipped.push({ id: rule.id, reason: "disabled by feature flags" });
      continue;
    }
    const keep = new Set(rule.keep ?? rule.keepFor?.({ platform, features }) ?? []);
    const matched = new Set<string>();
    for (const pattern of rule.remove) {
      for (const rel of new Bun.Glob(pattern).scanSync({ cwd: runtimeRoot, dot: true })) {
        if (!keep.has(rel)) matched.add(rel);
      }
    }
    if (matched.size === 0) continue;

    let bytes = 0;
    for (const rel of matched) {
      const abs = join(runtimeRoot, rel);
      if (!existsSync(abs)) continue;
      bytes += sizeOf(abs);
      if (!dryRun) rmSync(abs, { recursive: true, force: true });
    }
    report.removed.push({ id: rule.id, bytes, files: matched.size });
    report.totalBytes += bytes;
  }

  return report;
}

/**
 * Repacks omni.ja after dropping resources that cannot be deleted from disk.
 * Requires `unzip` and `zip`. This rewrites a signed-ish archive and must be
 * smoke-tested against the exact runtime version you ship.
 */
export async function repackOmni(
  runtimeRoot: string,
  features: FeatureConfig,
  opts: { dryRun?: boolean } = {},
): Promise<number> {
  if (features.devtools && features.pdf) return 0;
  let saved = 0;

  for (const archiveRel of ["omni.ja", "browser/omni.ja"]) {
    const archive = join(runtimeRoot, archiveRel);
    if (!existsSync(archive)) continue;

    const before = sizeOf(archive);
    const stage = `${archive}.stage`;
    if (!opts.dryRun) rmSync(stage, { recursive: true, force: true });

    if (!opts.dryRun) {
      if (!Bun.which("unzip") || !Bun.which("zip")) {
        throw new FireShellError(
          "repackOmni requires `unzip` and `zip` on PATH",
          "install zip/unzip, or set features.stripGecko.repackOmni = false",
        );
      }
      await run(["unzip", "-q", archive, "-d", stage], { dryRun: opts.dryRun });
      const drop = [
        ...(features.devtools ? [] : [`${archiveRel.startsWith("browser/") ? "" : ""}chrome/devtools`, "modules/devtools"]),
        ...(features.pdf ? [] : ["chrome/pdfjs", "resource/pdfjs", "pdfjs"]),
      ];
      for (const rel of drop) {
        for (const match of new Bun.Glob(`${rel}/**`).scanSync({ cwd: stage, dot: true })) {
          rmSync(join(stage, match), { recursive: true, force: true });
        }
        rmSync(join(stage, rel), { recursive: true, force: true });
      }
      const rebuilt = `${archive}.new`;
      await run(["zip", "-q", "-r", "-X", rebuilt, "."], { cwd: stage, dryRun: opts.dryRun });
      renameSync(rebuilt, archive);
      rmSync(stage, { recursive: true, force: true });
    }

    const after = opts.dryRun ? before : sizeOf(archive);
    saved += Math.max(0, before - after);
  }

  if (!opts.dryRun) log.dim(`omni repack saved ${human(saved)}`);
  return saved;
}

export function printPruneReport(report: PruneReport) {
  if (report.removed.length === 0) {
    log.dim("nothing pruned");
    return;
  }
  for (const entry of report.removed) {
    log.dim(`- ${entry.id}: ${entry.files} paths, ${human(entry.bytes)}`);
  }
  log.ok(`pruned ${human(report.totalBytes)} from the Gecko runtime`);
  for (const skip of report.skipped) log.dim(`- ${skip.id}: ${skip.reason}`);
}
