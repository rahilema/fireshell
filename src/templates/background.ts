/**
 * Background script that opens the app window.
 *
 * Used as the scaffold's `src/ui/background.js` and as the fallback the CLI generates when
 * a project does not provide one.
 *
 * Three behaviours it must get right:
 *  - dedupe: onInstalled, onStartup and the top-level call can all fire in the same tick,
 *    and each `windows.create()` resolves later, so a plain id check opens N windows.
 *  - reloads: web-ext reinstalls the add-on on file change, which discards in-memory state;
 *    an existing extension view is reused instead of opening another window.
 *  - dev harness: `web-ext run` starts Firefox with its own blank window. When the `tabs`
 *    permission is present (dev manifests only), that leftover window is closed so the
 *    app is the only thing on screen.
 */
export function backgroundScript(entry: string): string {
  return `// Generated by FireShell: opens the app window on install/startup.
// Replace it by adding your own src/ui/background.js.
var appWindowId = null;
var opening = null;
var ENTRY = ${JSON.stringify(entry)};

function entryUrl() {
  return browser.runtime.getURL(ENTRY);
}

function hasTabsPermission() {
  var permissions = (browser.runtime.getManifest().permissions || []);
  return permissions.indexOf("tabs") !== -1;
}

function existingView() {
  try {
    var views = browser.extension.getViews() || [];
    for (var i = 0; i < views.length; i++) {
      var view = views[i];
      if (view && view.location && view.location.href === entryUrl()) return view;
    }
  } catch (err) {
    // getViews is not available everywhere; fall through and open a window
  }
  return null;
}

/**
 * Closes the blank window the dev harness opens. Requires the tabs permission, which
 * only the dev manifest asks for; in a packaged build this is a no-op.
 */
function closeHarnessWindow() {
  if (!hasTabsPermission()) return Promise.resolve();
  return browser.windows
    .getAll({ populate: true })
    .then(function (windows) {
      var closing = [];
      for (var i = 0; i < windows.length; i++) {
        var win = windows[i];
        var tabs = win.tabs || [];
        if (win.id === appWindowId) continue;
        if (tabs.length !== 1) continue;
        if (tabs[0] && tabs[0].url === "about:blank") closing.push(browser.windows.remove(win.id));
      }
      return Promise.all(closing);
    })
    .catch(function () {
      // best effort: a stray window is not worth failing the launch
    });
}

function createWindow() {
  return browser.windows
    .create({ url: entryUrl(), type: "popup", width: 1200, height: 800 })
    .then(function (win) {
      appWindowId = win.id;
      return closeHarnessWindow();
    })
    .catch(function (err) {
      console.error("fireshell: cannot open the app window", err);
    });
}

function openAppWindow() {
  if (appWindowId !== null) {
    return browser.windows.update(appWindowId, { focused: true }).catch(function () {
      appWindowId = null;
      return openAppWindow();
    });
  }
  if (existingView()) return Promise.resolve();
  if (opening) return opening;
  opening = createWindow().then(
    function () { opening = null; },
    function () { opening = null; }
  );
  return opening;
}

browser.windows.onRemoved.addListener(function (id) {
  if (id === appWindowId) appWindowId = null;
});

browser.runtime.onStartup.addListener(openAppWindow);
browser.runtime.onInstalled.addListener(openAppWindow);
openAppWindow();
`;
}
